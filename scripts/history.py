"""Append-only recording journal plus backward-compatible prediction history."""
from __future__ import annotations

import json
import threading
from datetime import datetime
from pathlib import Path

from scripts.realtime_pipeline import append_jsonl


def now_iso():
    return datetime.now().astimezone().isoformat()


def read_jsonl(path):
    if not path.exists():
        return []
    rows = []
    with path.open(encoding="utf-8") as handle:
        for line in handle:
            try:
                row = json.loads(line)
                if isinstance(row, dict):
                    rows.append(row)
            except json.JSONDecodeError:
                # An interrupted final append must not hide older history.
                continue
    return rows


class History:
    def __init__(self, log_path: Path, journal_path: Path, video_dir: Path):
        self.log_path, self.journal_path, self.video_dir = log_path, journal_path, video_dir
        self.lock = threading.RLock()
        for directory in (log_path.parent, journal_path.parent, video_dir):
            directory.mkdir(parents=True, exist_ok=True)
            import tempfile
            with tempfile.TemporaryFile(dir=directory):
                pass
        self.records = {}
        for row in read_jsonl(journal_path):
            if "id" in row:
                self.records[row["id"]] = row

    def update(self, record_id, **fields):
        with self.lock:
            row = {**self.records.get(record_id, {}), "id": record_id, **fields}
            row.setdefault("recorded_at", now_iso())
            row["updated_at"] = now_iso()
            append_jsonl(self.journal_path, row)
            self.records[record_id] = row
            return dict(row)

    def recover(self):
        predictions = {row.get("trial_id") for row in read_jsonl(self.log_path)}
        for record_id, row in list(self.records.items()):
            if row.get("status") in {"recording", "finalizing", "collecting", "processing"}:
                if row.get("kind") == "trial" and record_id in predictions:
                    self.update(record_id, status="finished")
                else:
                    reason = "前回のサーバー終了により中断しました"
                    self.update(record_id, status="interrupted", error_message=reason)
                    if row.get("kind") == "trial":
                        append_jsonl(self.log_path, {"recorded_at": now_iso(), "trial_id": record_id,
                            "status": "interrupted", "error_message": reason,
                            "video_id": row.get("video_id")})

    def items(self):
        with self.lock:
            records = {key: dict(value) for key, value in self.records.items()}
        for prediction in read_jsonl(self.log_path):
            key = prediction.get("trial_id")
            if key:
                records[key] = {**records.get(key, {}), **prediction, "id": key, "kind": "trial"}
        for row in records.values():
            video_id = row.get("video_id")
            if video_id and video_id in records:
                video = records[video_id]
                row["video_status"] = video.get("status")
                row["video_error"] = video.get("error_message")
            elif row.get("kind") == "recording":
                row["video_id"] = row["id"]
                row["video_status"] = row.get("status")
            else:
                row["video_status"] = None
            row["video_available"] = bool(row.get("video_id") and self.video_path(row["video_id"]))
        return sorted(records.values(), key=lambda row: row.get("recorded_at", ""), reverse=True)

    def video_path(self, video_id):
        # Resolve only IDs generated by us. Never accept a filename from the client.
        import re
        if not re.fullmatch(r"video_[0-9a-f]{32}", video_id):
            return None
        with self.lock:
            row = self.records.get(video_id, {})
            if row.get("status") not in {"completed", "interrupted"}:
                return None
        path = self.video_dir / (video_id + ".mp4")
        return path if path.is_file() else None
